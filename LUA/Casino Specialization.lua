-------------------------TOTAL INCOME-------------------------------------------------------
function game.cam_get_total_gambling_income()
    local total = 0
    local gamingDepartmentID = hex2dec('9CF71EA3')
    if gamingDepartmentID then
        local income = tonumber(sc4game.budget.get_department_total_income(gamingDepartmentID), 10) or 0
        local expense = tonumber(sc4game.budget.get_department_total_expense(gamingDepartmentID), 10) or 0
        local departmentProfit = income - expense
        if game.ordinance_is_on(ordinance_ids.ORDINANCE_GAMBLING) then
            local gamblingOrdinanceIncome = game.ordinance_monthly_cost(ordinance_ids.ORDINANCE_GAMBLING) or 0
            total = departmentProfit + gamblingOrdinanceIncome
        end
    else
        print("WARNING: Invalid or void gambling department ID")
    end
    return total
end
-------------------------PROSTITUTE CALCULATION-------------------------------------------------------
function game.cam_get_prostitute()
    local mean = game.g_city_r_population / 100
    local std_dev = mean * 0.15
    local u1 = math.random()
    local u2 = math.random()
    local z = math.sqrt(-2 * math.log(u1)) * math.cos(2 * math.pi * u2)
    local civilian_count = math.floor(math.max(0, z * std_dev + mean) + 0.5)
    return civilian_count
end
-------------------------CRIMINAL-------------------------------------------------------
function game.cam_get_criminalcasino()
    local mean2 = game.g_criminal_count / 100
    local std_dev2 = mean2 * 0.25
    local t1 = math.random()
    local t2 = math.random()
    local z2 = math.sqrt(-2 * math.log(t1)) * math.cos(2 * math.pi * t2)
    local criminal_count = math.floor(math.max(0, z2 * std_dev2 + mean2) + 0.5)
    return criminal_count
end
